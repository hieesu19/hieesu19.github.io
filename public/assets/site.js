 const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
 const sidebar = $('#sidebar'), shade = $('#mobile-shade');
 const closeSide = () => { sidebar?.classList.remove('mobile-visible'); shade?.classList.remove('active'); document.body.classList.remove('lock-scroll'); };
